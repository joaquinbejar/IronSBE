//! Main code generator orchestration.

use ironsbe_schema::ir::SchemaIr;

use crate::error::CodegenError;
use crate::options::GeneratorOptions;
use crate::rust::{EnumGenerator, MessageGenerator, TypeGenerator};

/// Main code generator for SBE schemas.
pub struct Generator<'a> {
    ir: &'a SchemaIr,
    options: GeneratorOptions,
}

impl<'a> Generator<'a> {
    /// Creates a new generator for the given schema IR.
    #[must_use]
    pub fn new(ir: &'a SchemaIr) -> Self {
        Self::with_options(ir, GeneratorOptions::default())
    }

    /// Creates a new generator for the given schema IR with explicit
    /// options; see [`GeneratorOptions`].
    #[must_use]
    pub fn with_options(ir: &'a SchemaIr, options: GeneratorOptions) -> Self {
        Self { ir, options }
    }

    /// Generates the complete Rust code for the schema.
    ///
    /// # Errors
    /// Returns [`CodegenError::Unsupported`] when the schema uses a construct
    /// the generator cannot emit correct code for (for example `<data>` inside
    /// a repeating group), and [`CodegenError::UnknownType`] when a `<data>`
    /// element references a type that is not declared in `<types>`.
    pub fn generate(&self) -> Result<String, CodegenError> {
        let mut output = String::with_capacity(64 * 1024);

        // Constants
        self.generate_constants(&mut output);

        // Types (enums, sets, composites)
        let type_gen = TypeGenerator::new(self.ir);
        output.push_str(&type_gen.generate());

        // Enums
        let enum_gen = EnumGenerator::new(self.ir);
        output.push_str(&enum_gen.generate());

        // Messages
        let msg_gen = MessageGenerator::with_options(self.ir, self.options);
        output.push_str(&msg_gen.generate()?);

        // The file header last, so it imports only what the body uses: an
        // unused import is an error under a downstream `-D warnings`.
        let mut file = String::with_capacity(output.len() + 512);
        self.generate_header(&mut file, &output);
        file.push_str(&output);
        Ok(file)
    }

    /// Generates the file header with the imports `body` uses. The buffer
    /// traits are always imported: their methods are called by name, not
    /// named.
    fn generate_header(&self, output: &mut String, body: &str) {
        output.push_str("// Generated by IronSBE codegen - DO NOT EDIT\n");
        output.push_str(&format!(
            "// Schema: {} v{}\n",
            self.ir.package, self.ir.schema_version
        ));
        output.push('\n');
        let uses = |name: &str| body.contains(name);
        let headers: Vec<&str> = ["MessageHeader", "GroupHeader", "VarDataHeader"]
            .into_iter()
            .filter(|name| uses(name))
            .collect();
        let decoders: Vec<&str> = ["SbeDecoder", "DecodeError"]
            .into_iter()
            .filter(|name| uses(name))
            .collect();
        output.push_str("use ironsbe_core::{\n");
        output.push_str("    buffer::{ReadBuffer, WriteBuffer},\n");
        if !headers.is_empty() {
            output.push_str(&format!("    header::{{{}}},\n", headers.join(", ")));
        }
        if !decoders.is_empty() {
            output.push_str(&format!("    decoder::{{{}}},\n", decoders.join(", ")));
        }
        if uses("SbeEncoder") {
            output.push_str("    encoder::SbeEncoder,\n");
        }
        output.push_str("};\n");
        output.push('\n');
    }

    /// Generates schema constants.
    fn generate_constants(&self, output: &mut String) {
        output.push_str(&format!(
            "/// Schema ID for this protocol.\n\
             pub const SCHEMA_ID: u16 = {};\n",
            self.ir.schema_id
        ));
        output.push_str(&format!(
            "/// Schema version for this protocol.\n\
             pub const SCHEMA_VERSION: u16 = {};\n",
            self.ir.schema_version
        ));
        output.push('\n');
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use ironsbe_schema::parse_schema;

    #[test]
    fn test_generate_simple_schema() {
        let xml = r#"<?xml version="1.0" encoding="UTF-8"?>
<sbe:messageSchema xmlns:sbe="http://fixprotocol.io/2016/sbe"
                   package="test" id="1" version="1" byteOrder="littleEndian">
    <types>
        <type name="uint64" primitiveType="uint64"/>
    </types>
    <sbe:message name="TestMessage" id="1" blockLength="8">
        <field name="value" id="1" type="uint64" offset="0"/>
    </sbe:message>
</sbe:messageSchema>"#;

        let schema = parse_schema(xml).expect("Failed to parse");
        let ir = SchemaIr::from_schema(&schema);
        let generator = Generator::new(&ir);
        let code = generator.generate().expect("codegen failed");

        assert!(code.contains("SCHEMA_ID: u16 = 1"));
        assert!(code.contains("SCHEMA_VERSION: u16 = 1"));
        assert!(code.contains("TestMessageDecoder"));
        assert!(code.contains("TestMessageEncoder"));
    }
}
